CREATE TABLE IF NOT EXISTS bank_soal_metadata (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS questions (
  id text PRIMARY KEY,
  data jsonb NOT NULL,
  updated timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS question_versions (
  question_id text NOT NULL REFERENCES questions(id),
  version integer NOT NULL CHECK (version > 0),
  created timestamptz NOT NULL,
  actor text NOT NULL,
  note text NOT NULL,
  snapshot jsonb NOT NULL,
  PRIMARY KEY (question_id, version)
);

CREATE TABLE IF NOT EXISTS exam_packages (
  id text PRIMARY KEY,
  name text NOT NULL,
  course text NOT NULL,
  created timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS package_items (
  package_id text NOT NULL REFERENCES exam_packages(id),
  question_id text NOT NULL,
  version integer NOT NULL,
  position integer NOT NULL CHECK (position >= 0),
  PRIMARY KEY (package_id, question_id),
  FOREIGN KEY (question_id, version) REFERENCES question_versions(question_id, version)
);

CREATE INDEX IF NOT EXISTS package_items_question ON package_items(question_id);

CREATE TABLE IF NOT EXISTS audit_entries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action text NOT NULL,
  entity_id text NOT NULL,
  title text NOT NULL,
  version integer,
  actor text NOT NULL,
  created timestamptz NOT NULL,
  note text NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS audit_entity ON audit_entries(entity_id);

CREATE TABLE IF NOT EXISTS auth_users (
  username text PRIMARY KEY CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,39}$'),
  display_name text NOT NULL,
  password_salt bytea NOT NULL CHECK (octet_length(password_salt) = 16),
  password_hash bytea NOT NULL CHECK (octet_length(password_hash) = 64)
);

CREATE TABLE IF NOT EXISTS auth_sessions (
  token_hash bytea PRIMARY KEY CHECK (octet_length(token_hash) = 32),
  username text NOT NULL REFERENCES auth_users(username) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS auth_sessions_expiration ON auth_sessions(expires_at);
